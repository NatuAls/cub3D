#include "libft.h"

int	ft_putstr_fd(char *s, int fd)
{
	int	i;

	if (fd >= 0 && s)
	{
		i = 0;
		while (s[i] != '\0')
		{
			if (ft_putchar_fd(s[i], fd) == -1)
				return (-1);
			i++;
		}
	}
	return (1);
}
